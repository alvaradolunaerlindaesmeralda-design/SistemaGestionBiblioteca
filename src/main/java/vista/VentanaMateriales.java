    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {
    String codigo = txtCodigo.getText().trim();
    String titulo = txtTitulo.getText().trim();
    int anio = Integer.parseInt(txtAnio.getText().trim());

    String tipo = cmbTipoMaterial.getSelectedItem().toString();

    MaterialServicio servicio = new MaterialServicio();

    if (tipo.equals("Libro")) {

        String autor = txtEditorial.getText().trim();
String editorial = jTextField2.getText().trim();

        Libro libro = new Libro(
                codigo, titulo, anio, autor, editorial
        );

        servicio.registrarLibro(libro);

    } else if (tipo.equals("Revista")) {

        int numeroEdicion = Integer.parseInt(
                txtNumeroEdicion.getText().trim()
        );

        String periodicidad = txtPeriodicidad.getText().trim();

        Revista revista = new Revista(
                codigo, titulo, anio, numeroEdicion, periodicidad
        );

        servicio.registrarRevista(revista);
    }

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Material registrado correctamente."
    );

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "El año y el número de edición deben ser números."
    );

} catch (IllegalArgumentException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            e.getMessage()
    );

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error al registrar el material: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnRegistrarActionPerformed

